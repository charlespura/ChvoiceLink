import fs from "node:fs";
import path from "node:path";

function parseEnvFile(contents) {
  const out = {};
  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const root = process.cwd();
const envPath = path.join(root, ".env");
const outPath = path.join(root, "env.js");

if (!fs.existsSync(envPath)) {
  console.error(
    "Missing .env. Copy .env.example -> .env and fill in your Firebase web config.",
  );
  process.exit(1);
}

const env = parseEnvFile(fs.readFileSync(envPath, "utf8"));

const required = [
  "FIREBASE_API_KEY",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_STORAGE_BUCKET",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_APP_ID",
  "FIREBASE_MEASUREMENT_ID",
];

const missing = required.filter((k) => !env[k]);
if (missing.length) {
  console.error(`Missing keys in .env: ${missing.join(", ")}`);
  process.exit(1);
}

const js =
  `// AUTO-GENERATED by scripts/gen-firebase-config.mjs (do not commit this file)\n` +
  `// This file must be served as a static asset and loaded before src/main.js.\n` +
  `globalThis.__FIREBASE_CONFIG__ = {\n` +
  `  apiKey: ${JSON.stringify(env.FIREBASE_API_KEY)},\n` +
  `  authDomain: ${JSON.stringify(env.FIREBASE_AUTH_DOMAIN)},\n` +
  `  projectId: ${JSON.stringify(env.FIREBASE_PROJECT_ID)},\n` +
  `  storageBucket: ${JSON.stringify(env.FIREBASE_STORAGE_BUCKET)},\n` +
  `  messagingSenderId: ${JSON.stringify(env.FIREBASE_MESSAGING_SENDER_ID)},\n` +
  `  appId: ${JSON.stringify(env.FIREBASE_APP_ID)},\n` +
  `  measurementId: ${JSON.stringify(env.FIREBASE_MEASUREMENT_ID)},\n` +
  `};\n`;

fs.writeFileSync(outPath, js, "utf8");
console.log(`Wrote ${path.relative(root, outPath)}`);
